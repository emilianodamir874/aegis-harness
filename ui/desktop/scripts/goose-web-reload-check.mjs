import { readFile } from 'node:fs/promises';
import { chromium } from '@playwright/test';
const cfg = JSON.parse(await readFile('C:/goose-web/config.json', 'utf8'));
const url = 'http://' + cfg.publicHost + ':' + cfg.webPort + '/';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1000, height: 700 } });
await page.goto(url);
await page.waitForFunction(() => window.__gooseWeb && window.__gooseWeb.rpc && window.__gooseWeb.rpc.ready, null, { timeout: 30000 });
await page.waitForTimeout(2500);
const sid = await page.evaluate(() => { const b = document.querySelector('#btn-new'); b.click(); return 1; });
await page.waitForTimeout(2500);
const s0 = await page.evaluate(() => (window.__gooseWeb.state.current || {}).id);
await page.fill('#input', 'Usá execute_typescript con este código exacto: await new Promise(r => setTimeout(r, 22000)); y después respondé solo OK.');
await page.click('#btn-send');
await page.waitForTimeout(7000);
const antes = await page.evaluate(() => ({ run: !!document.querySelector('.runbar'), n: document.querySelectorAll('#msg-inner .msg-a').length }));
console.log('SID ' + s0 + ' ANTES_RELOAD ' + JSON.stringify(antes));
await page.reload({ waitUntil: 'load' });
await page.waitForTimeout(12000);
const tras1 = await page.evaluate(() => ({ run: !!document.querySelector('.runbar'), runTxt: (document.querySelector('.runbar') || {}).textContent || '', n: document.querySelectorAll('#msg-inner .msg-a').length }));
console.log('TRAS_RELOAD_12s ' + JSON.stringify(tras1));
await page.waitForTimeout(32000);
const tras2 = await page.evaluate(() => {
  const ms = [...document.querySelectorAll('#msg-inner .msg-a')];
  const ult = ms.length ? ms[ms.length - 1].textContent.slice(0, 120) : '';
  return { run: !!document.querySelector('.runbar'), n: ms.length, ult, tools: document.querySelectorAll('#msg-inner .tool').length };
});
console.log('TRAS_44s ' + JSON.stringify(tras2));
await browser.close();
process.exit(0);
