import { chromium } from 'playwright';
const br = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
const p = await (await br.newContext({ viewport: { width: 430, height: 900 } })).newPage();
const errs = [];
p.on('pageerror', (e) => errs.push(String(e.message).slice(0, 140)));
await p.goto('http://127.0.0.1:3788/', { waitUntil: 'load' });
await p.waitForFunction(() => window.__aegisWeb && window.__aegisWeb.read, null, { timeout: 20000 });
await p.evaluate(() => {
  window.__dev = [];
  Object.defineProperty(window, 'speechSynthesis', { configurable: true, writable: true, value: { speak: (u) => window.__dev.push(String(u.text)), cancel: () => {}, getVoices: () => [], addEventListener: () => {} } });
  Object.defineProperty(window, 'SpeechSynthesisUtterance', { configurable: true, writable: true, value: function (t) { this.text = t; } });
});
console.log('--- A) server OK: usa Piper, no la voz del dispositivo ---');
await p.evaluate(() => window.__aegisWeb.read.toggle(true));
await p.evaluate((t) => window.__aegisWeb.read.pump('k1', t), '## Para escuchar\nFrase de prueba con el server andando.');
await p.waitForTimeout(4000);
console.log('   voz del dispositivo usada: ' + JSON.stringify(await p.evaluate(() => window.__dev)) + ' | fallos: ' + (await p.evaluate(() => window.__aegisWeb.read.state().fallos)));
console.log('--- B) server caido (500): debe quedarse MUDO, no caer al telefono ---');
await p.route('**/tts?**', (r) => r.fulfill({ status: 500, body: 'caido' }));
await p.evaluate(() => window.__aegisWeb.read.toggle(false));
await p.evaluate(() => window.__aegisWeb.read.toggle(true));
await p.evaluate((t) => window.__aegisWeb.read.pump('k2', t), '## Para escuchar\nCon el server caido no deberia sonar la voz vieja.');
await p.waitForTimeout(4000);
const st = await p.evaluate(() => window.__aegisWeb.read.state());
const nota = await p.evaluate(() => { const n = [...document.querySelectorAll('.sysnote')].map((e) => e.textContent); return n.slice(-1); });
console.log('   voz del dispositivo usada: ' + JSON.stringify(await p.evaluate(() => window.__dev)) + ' | fallos: ' + st.fallos);
console.log('   aviso en pantalla: ' + JSON.stringify(nota));
console.log('errores: ' + JSON.stringify(errs));
await br.close();
