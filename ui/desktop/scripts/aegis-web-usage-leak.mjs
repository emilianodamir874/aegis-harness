import { readFile } from 'node:fs/promises';
import { chromium } from '@playwright/test';
const cfg = JSON.parse(await readFile('C:/Aegis-Proyects/web/config.json', 'utf8'));
const url = 'http://' + cfg.publicHost + ':' + cfg.webPort + '/';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1000, height: 700 }, deviceScaleFactor: 2 });
await page.addInitScript(([k, v]) => { try { localStorage.setItem(k, v); } catch {} }, ['gweb.last', '20261012_25']);
await page.goto(url);
await page.waitForFunction(() => window.__aegisWeb && window.__aegisWeb.rpc && window.__aegisWeb.rpc.ready, null, { timeout: 30000 });
await page.waitForTimeout(9000);
const antes = await page.evaluate(() => document.querySelector('#meta-right').textContent);
await page.click('#btn-new');
await page.waitForTimeout(2500);
const despues = await page.evaluate(() => ({ txt: document.querySelector('#meta-right').textContent, usage: window.__aegisWeb.usageState() }));
console.log('ANTES  ' + JSON.stringify(antes));
console.log('DESPUES ' + JSON.stringify(despues));
await browser.close();
process.exit(0);
